import { useState } from 'react';

/**
 * 初回のレンダリングで作成した値を、アンマウントされるまで返し続けるhook
 *
 * `useMemo`はパフォーマンス最適化のためのhookであり、キャッシュが破棄されないことは保証されていない。
 * 状態を持つインスタンスなど、同一であることが動作の前提となる値はこのhookで保持する。
 *
 * 同じ値を返し続けることを保証するのは、コミットした後だけである。
 * `factory` はレンダリング中に呼ばれるため、コミットする前に複数回呼ばれ、作った値が捨てられることがある。
 * - StrictMode（開発時）では、レンダリングが2回行われ、一方の結果は捨てられる
 * - トランジションの中断や Suspense で捨てられたレンダリングで作った値も、捨てられる
 *
 * 捨てられた値の後片付けは行われないため、`factory` では外部に影響を与える処理
 * （DOM の操作、イベントの登録、タイマー、通信など）をしないこと。
 * そのような処理を伴うインスタンスは、エフェクトの中で作り、エフェクトの後片付けで破棄する。
 *
 * @param factory 値を作成する関数。初回のレンダリングで呼ばれる（コミットする前に複数回呼ばれることがある）
 * @returns 値
 */
export default function useConstant<T>(factory: () => T): T {
  // useStateの初期値はアンマウントされるまで保持されることが保証されている
  const [value] = useState(factory);
  return value;
}
